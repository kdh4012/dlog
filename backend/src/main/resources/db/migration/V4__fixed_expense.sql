-- 고정지출 템플릿. 등록해 두면 start_month 부터 (end_month 까지) 매월 지출 내역으로 반영된다
CREATE TABLE fixed_expense
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    amount         BIGINT       NOT NULL,
    day_of_month   INT          NOT NULL, -- 1~31. 그 달에 없는 날이면 말일
    category       VARCHAR(20)  NOT NULL,
    payment_method VARCHAR(20)  NOT NULL,
    start_month    VARCHAR(7)   NOT NULL, -- yyyy-MM
    end_month      VARCHAR(7),            -- yyyy-MM, null 이면 계속
    memo           VARCHAR(500),
    created_at     TIMESTAMP    NOT NULL,
    updated_at     TIMESTAMP    NOT NULL
);

-- 고정지출을 어느 달에 반영했는지 기록. 반영된 지출을 지워도 이 기록이 남아 다시 생성되지 않는다
CREATE TABLE fixed_expense_run
(
    fixed_expense_id BIGINT     NOT NULL REFERENCES fixed_expense (id) ON DELETE CASCADE,
    run_month        VARCHAR(7) NOT NULL,
    PRIMARY KEY (fixed_expense_id, run_month)
);

-- 지출 구분. FIXED: 고정지출에서 반영된 내역, VARIABLE: 직접 입력한 변동지출
ALTER TABLE expense ADD COLUMN kind VARCHAR(10) NOT NULL DEFAULT 'VARIABLE';
-- 반영 원본. 고정지출을 삭제해도 지난 내역은 고정지출(kind)로 남는다
ALTER TABLE expense ADD COLUMN fixed_expense_id BIGINT REFERENCES fixed_expense (id) ON DELETE SET NULL;
