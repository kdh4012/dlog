-- 가계부를 '월 수입 · 월 고정지출 · 부채 잔액' 항목 관리로 변경
CREATE TABLE ledger_item
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind       VARCHAR(20)  NOT NULL, -- INCOME: 월 수입, FIXED_EXPENSE: 월 고정지출, DEBT: 부채 잔액
    name       VARCHAR(100) NOT NULL,
    amount     BIGINT       NOT NULL, -- 원 단위
    memo       VARCHAR(500),
    created_at TIMESTAMP    NOT NULL,
    updated_at TIMESTAMP    NOT NULL
);

-- 아직 끝나지 않은 고정지출만 옮긴다
INSERT INTO ledger_item (kind, name, amount, memo, created_at, updated_at)
SELECT 'FIXED_EXPENSE', name, amount, memo, created_at, updated_at
FROM fixed_expense
WHERE end_month IS NULL
   OR end_month >= TO_CHAR(CURRENT_DATE, 'YYYY-MM');

